// Compiles contracts/IroncladToken.sol and writes the browser bundle the Forge uses.
// Usage: npm install && npm run build:contract
const fs = require("fs");
const path = require("path");
const solc = require("solc");

const root = path.join(__dirname, "..");
const source = fs.readFileSync(path.join(root, "contracts/IroncladToken.sol"), "utf8");
const input = {
  language: "Solidity",
  sources: { "IroncladToken.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors || []).filter((e) => e.severity === "error");
if (errors.length) {
  errors.forEach((e) => console.error(e.formattedMessage));
  process.exit(1);
}
const c = out.contracts["IroncladToken.sol"].IroncladToken;
const artifact = {
  compiler: "solc " + solc.version().split("+")[0] + ", optimizer 200 runs, evm paris",
  abi: c.abi,
  bytecode: "0x" + c.evm.bytecode.object,
};
fs.writeFileSync(path.join(root, "contracts/IroncladToken.json"), JSON.stringify(artifact, null, 1) + "\n");
fs.writeFileSync(
  path.join(root, "assets/forge-artifact.js"),
  "/* Generated by scripts/build-contract.js. Do not edit. */\nwindow.IRONCLAD_ARTIFACT = " +
    JSON.stringify({ compiler: artifact.compiler, bytecode: artifact.bytecode, source }) +
    ";\n"
);
console.log("IroncladToken: " + (c.evm.bytecode.object.length / 2) + " bytes");
